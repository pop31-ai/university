function totalArticles() {
  let n = 0;
  for (const area of Object.keys(UNIVERSE)) n += UNIVERSE[area].length;
  return n * ROLES.length; // темы x роли
}

// Плоский список статей в фиксированном порядке:
// для каждой области, для каждой её темы — по одной статье на каждую роль.
function buildArticles() {
  const list = [];
  const areas = Object.keys(UNIVERSE);
  for (const area of areas) {
    for (const topic of UNIVERSE[area]) {
      for (const role of ROLES) {
        list.push({ area, topic, role });
      }
    }
  }
  return list;
}

